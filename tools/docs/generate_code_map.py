#!/usr/bin/env python3
"""Generate a compact inventory of every authored code/config/scene file."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "reference" / "code-map.md"
EXTENSIONS = {".gd", ".godot", ".py", ".sh", ".gdshader", ".tscn", ".cfg"}
SKIP_PARTS = {".git", ".godot", "build", "venv", "preview"}


def authored_files() -> list[Path]:
    return sorted(
        path for path in ROOT.rglob("*")
        if path.is_file()
        and path.suffix in EXTENSIONS
        and not any(part in SKIP_PARTS for part in path.relative_to(ROOT).parts)
    )


def description(path: Path, text: str) -> str:
    class_match = re.search(r"(?m)^class_name\s+(\w+)", text)
    for line in text.splitlines()[:30]:
        stripped = line.strip()
        if stripped.startswith("## "):
            return stripped[3:].replace("|", "\\|")
        if stripped.startswith('"""') and len(stripped) > 3:
            return stripped.strip('"').replace("|", "\\|")
        if stripped.startswith("# ") and path.suffix == ".sh":
            return stripped[2:].replace("|", "\\|")
    if class_match:
        return f"`{class_match.group(1)}`"
    if path.suffix == ".tscn":
        return "Godot scene"
    if path.suffix == ".gdshader":
        return "Godot shader"
    return "Authored project file"


def symbol_summary(text: str, suffix: str) -> str:
    if suffix == ".gd":
        funcs = re.findall(r"(?m)^(?:static\s+)?func\s+(\w+)", text)
        classes = re.findall(r"(?m)^class_name\s+(\w+)", text)
        head = f"class `{classes[0]}`; " if classes else ""
        return f"{head}{len(funcs)} functions"
    if suffix == ".py":
        functions = re.findall(r"(?m)^def\s+(\w+)", text)
        return f"{len(functions)} functions"
    if suffix == ".tscn":
        nodes = re.findall(r"(?m)^\[node\s", text)
        return f"{len(nodes)} nodes"
    return "—"


def render() -> str:
    files = authored_files()
    groups: dict[str, list[Path]] = {}
    for path in files:
        rel = path.relative_to(ROOT)
        group = rel.parts[0] if len(rel.parts) > 1 else "root"
        groups.setdefault(group, []).append(path)
    lines = [
        "# Generated code map",
        "",
        "> Generated by `tools/docs/generate_code_map.py`. Do not edit by hand.",
        "",
        f"Inventory: **{len(files)} authored code/config/scene files**.",
        "",
    ]
    for group, paths in groups.items():
        lines += [f"## {group}", "", "| File | Lines | Symbols | Purpose |",
                  "|---|---:|---|---|"]
        for path in paths:
            rel = path.relative_to(ROOT).as_posix()
            text = path.read_text(encoding="utf-8", errors="replace")
            line_count = len(text.splitlines())
            lines.append(
                f"| `{rel}` | {line_count} | {symbol_summary(text, path.suffix)} "
                f"| {description(path, text)} |"
            )
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print("docs/reference/code-map.md is stale; regenerate it.")
            return 1
        print("code map is current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

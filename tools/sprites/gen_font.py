def build_charset():
    chars = {}
    for ch, body in G.items():
        if len(ch) == 1:
            chars[ch] = list(body)
    chars["×"] = list(G["x_mult"])       # × multiplication sign
    for ch, base, _accent in COMPOSED:
        chars[ch] = list(G[base])
    for ch, base, _mark in BELOW_COMPOSED:
        chars[ch] = list(G[base])
    return chars


def render():
    chars = build_charset()
    ordered = sorted(chars.keys(), key=ord)
    cols = 16
    rows = (len(ordered) + cols - 1) // cols
    atlas = Image.new("RGBA", (cols * CELL_W, rows * CELL_H), (0, 0, 0, 0))

    accent_of = {ch: acc for ch, _base, acc in COMPOSED}
    below_of = {ch: mark for ch, _base, mark in BELOW_COMPOSED}

    entries = []
    for i, ch in enumerate(ordered):
        cx = (i % cols) * CELL_W
        cy = (i // cols) * CELL_H
        body = chars[ch]
        for ry, row in enumerate(body):
            for rx, cell in enumerate(row):
                if cell == "#":
                    atlas.putpixel((cx + rx, cy + BODY_TOP + ry), INK)
        if ch in accent_of:
            for ry, row in enumerate(ACCENTS[accent_of[ch]]):
                for rx, cell in enumerate(row):
                    if cell == "#":
                        atlas.putpixel((cx + rx, cy + ry), INK)
        if ch in below_of:
            for dx, dy in BELOW[below_of[ch]]:
                atlas.putpixel((cx + dx, cy + BODY_TOP + 7 + dy), INK)
        entries.append((ch, cx, cy))

    os.makedirs(OUT_SPRITES, exist_ok=True)
    png_name = "harbor_font.png"
    atlas.save(os.path.join(OUT_SPRITES, png_name))

    # BMFont text descriptor — Godot imports this directly as a FontFile
    lines = [
        'info face="HarborPixel" size=%d bold=0 italic=0 charset="" unicode=1 '
        'stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1' % CELL_H,
        'common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0'
        % (CELL_H + 1, BODY_TOP + 7, atlas.width, atlas.height),
        'page id=0 file="%s"' % png_name,
        'chars count=%d' % len(entries),
    ]
    for ch, cx, cy in entries:
        lines.append(
            'char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 '
            'xadvance=%d page=0 chnl=15'
            % (ord(ch), cx, cy, CELL_W, CELL_H, CELL_W))
    with open(os.path.join(OUT_SPRITES, "harbor_font.fnt"), "w",
              encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("  harbor_font.png  %dx%d  (%d glyphs)"
          % (atlas.width, atlas.height, len(entries)))


